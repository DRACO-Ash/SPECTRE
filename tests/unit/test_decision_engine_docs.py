"""The Decision Engine's two written descriptions say what the engine does as built (SPC-152).

docs/decision_engine_phases.md is the design record: it keeps the game tree's design decisions D1 to D11, the
Threat Understanding concept's section 9 decisions the engine rests on, and each phase's gate. The operator guide's
Decision Engine section, generated by docs/generate_guide.py, is the operator's: it names every capability an
operator meets on the panel and in the results. Both follow the house style: no long dashes, no horizontal rules,
bullets as filled circles or squares.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

_ROOT = Path(__file__).resolve().parents[2]


def _read(relative: str) -> str:
    path = _ROOT / relative
    if not path.exists():
        pytest.skip(f"{relative} not present in this checkout")
    return path.read_text(encoding="utf-8")


def _guide_section() -> str:
    source = _read("docs/generate_guide.py")
    start = source.index("def _section_13_decision_engine")
    return " ".join(source[start:source.index("def _section_14_training", start)].split())


def _flat(text: str) -> str:
    return " ".join(text.split())


class TestThePhaseDocument:
    def test_it_keeps_the_eleven_design_decisions(self) -> None:
        doc = _read("docs/decision_engine_phases.md")
        for n in range(1, 12):
            assert re.search(rf"\*\*D{n}\. ", doc), f"D{n} is not recorded"

    def test_it_records_the_views_own_decisions(self) -> None:
        doc = _read("docs/decision_engine_phases.md")
        assert "Decisions taken building the view (SPC-142)" in doc

    @pytest.mark.parametrize("decision", [9, 10, 11, 12, 13, 16, 17, 18])
    def test_it_cross_refers_the_concepts_section_9_decisions(self, decision: int) -> None:
        doc = _flat(_read("docs/decision_engine_phases.md"))
        assert re.search(rf"decision {decision} \(", doc), f"concept section 9, decision {decision}"
        assert "section 9" in doc

    @pytest.mark.parametrize(
        "topic",
        [
            "Bound", "Computed", "Sampled", "Lookup", "Our response burns", "collect first", "Threat range",
            "Load from NOTSO", "95 in 100 Poisson interval", "turn depth", "update after turn 1",
            "deepest turn built in full", "What remains out of scope",
        ],
    )
    def test_it_describes_the_engine_as_built(self, topic: str) -> None:
        assert topic.lower() in _flat(_read("docs/decision_engine_phases.md")).lower()

    def test_it_follows_the_house_style(self) -> None:
        doc = _read("docs/decision_engine_phases.md")
        assert "—" not in doc and "–" not in doc
        assert not re.search(r"^(---|\*\*\*|___)\s*$", doc, re.MULTILINE), "a horizontal rule"
        assert not re.search(r"^\s*[-*] ", doc, re.MULTILINE), "a dash or star bullet"
        assert "--" not in doc.replace("|-------|", "").replace("----", "")


