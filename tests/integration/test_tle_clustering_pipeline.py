"""Integration tests for the TLE clustering pipeline.

Exercises the full path from raw multi-provider TLE strings through
:func:`spectre.astro.tle_preprocessing.cluster_and_reduce_tle_cache` to a
reduced ``hrr_tle_cache``.

Tests use synthetic TLEs generated by the same helper used in the unit
tests so the checksums and column alignment are guaranteed correct.
"""

from __future__ import annotations

# ---------------------------------------------------------------------------
# Shared TLE builder (mirrors tests/unit/tle_clustering/conftest.py)
# ---------------------------------------------------------------------------

_EPOCH = "26091.50000000"


def _checksum(line: str) -> int:
    total = 0
    for ch in line[:-1]:
        if ch.isdigit():
            total += int(ch)
        elif ch == "-":
            total += 1
    return total % 10


def _make_tle_pair(norad: int, inc: float, raan: float, ecc: float) -> tuple[str, str]:
    n = f"{norad:05d}"
    ecc_str = f"{ecc:.7f}"[2:]
    l1_body = (
        f"1 {n}U 98067A   {_EPOCH}"
        f"  .00000000"
        f"  00000-0"
        f"  00000-0"
        f" 0  999"
    )
    l1 = l1_body + str(_checksum(l1_body + "0"))
    l2_body = (
        f"2 {n} "
        f"{inc:8.4f} "
        f"{raan:8.4f} "
        f"{ecc_str} "
        f"100.0000 "
        f"200.0000 "
        f"15.5432109800001"
    )
    l2 = l2_body + str(_checksum(l2_body + "0"))
    return l1, l2


def _tle_string(norad: int, inc: float, raan: float, ecc: float) -> str:
    l1, l2 = _make_tle_pair(norad, inc, raan, ecc)
    return f"{l1}\n{l2}"


# ---------------------------------------------------------------------------
# Fixtures
# ---------------------------------------------------------------------------

_TLES_A = [
    # NORAD 25544 — five tight TLEs, all within default tolerances → 1 cluster
    _tle_string(25544, 51.6400, 247.1234, 0.0001234),
    _tle_string(25544, 51.6405, 247.1244, 0.0001239),
    _tle_string(25544, 51.6398, 247.1220, 0.0001230),
    _tle_string(25544, 51.6403, 247.1250, 0.0001237),
    _tle_string(25544, 51.6401, 247.1240, 0.0001236),
]

_TLES_B = [
    # NORAD 43013 — two tight TLEs → 1 cluster
    _tle_string(43013, 98.2000, 100.0000, 0.0008000),
    _tle_string(43013, 98.2002, 100.0010, 0.0007999),
]

_TLES_C = [
    # NORAD 99001 — two TLEs spread far apart → 2 noise items (no cluster forms)
    _tle_string(99001, 28.5000, 45.0000, 0.0003000),
    _tle_string(99001, 51.6000, 247.0000, 0.0001000),
]

_EXISTING_CACHE = {
    "25544": _tle_string(25544, 51.6400, 247.1234, 0.0001234),
    "43013": _tle_string(43013, 98.2000, 100.0000, 0.0008000),
    "99001": _tle_string(99001, 28.5000, 45.0000, 0.0003000),
    "77777": _tle_string(12345, 35.0000, 55.0000, 0.0002000),  # not in multiset
}

_MULTISET = {
    "25544": _TLES_A,
    "43013": _TLES_B,
    "99001": _TLES_C,
}

_CONFIG = {
    "inclination_tolerance_deg": 0.01,
    "raan_tolerance_deg": 0.05,
    "eccentricity_tolerance": 1e-4,
    "dbscan_min_samples": 2,
    "fetch_window_hours": 24,
}


